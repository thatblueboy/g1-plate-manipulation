"""Convert our .npy datasets (demos, recoveries) to GR00T-flavoured LeRobot v2.

    uv run python -m submission.groot.convert_dataset \
        --data datasets/move_plate datasets/recovery --out datasets/groot/move_plate_r1

Each input root holds rgb.npy (N, cams, 3, 84, 84), state.npy (N, 50),
action.npy (N, 20, raw units) and episode_ends.npy, with observation t paired
with the action executed after it (submission/act/export_dataset.py,
submission/act/pack_recoveries.py). Rows are copied unchanged; the named-key
layout lives in submission/groot/layout.py and is written to meta/modality.json.

Videos are H.264, yuv444p, CRF 0 (mean error 0.4/255; no chroma subsampling at
84x84) because the policy sees uncompressed frames at evaluation time.
--check decodes every video again and reports the reconstruction error.
meta/stats.json is generated by GR00T on the first fine-tuning run.
"""

import argparse
import json
import shutil
from pathlib import Path

import imageio_ffmpeg
import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

from submission.groot.layout import CAMERAS, FPS, TASK, modality_json

CHUNK = 1000
CRF = "0"


def write_video(path: Path, frames: np.ndarray) -> None:
    """frames: (T, H, W, 3) uint8."""
    path.parent.mkdir(parents=True, exist_ok=True)
    h, w = frames.shape[1:3]
    writer = imageio_ffmpeg.write_frames(
        str(path),
        (w, h),
        fps=FPS,
        codec="libx264",
        pix_fmt_in="rgb24",
        pix_fmt_out="yuv444p",
        output_params=["-crf", CRF, "-g", "10"],
        macro_block_size=1,
    )
    writer.send(None)
    for f in frames:
        writer.send(np.ascontiguousarray(f))
    writer.close()


def read_video(path: Path) -> np.ndarray:
    gen = imageio_ffmpeg.read_frames(str(path), pix_fmt="rgb24")
    meta = next(gen)
    w, h = meta["size"]
    return np.stack([np.frombuffer(b, np.uint8).reshape(h, w, 3) for b in gen])


def feature_info(n_state: int, n_action: int, h: int, w: int) -> dict:
    video = {
        "dtype": "video",
        "shape": [h, w, 3],
        "names": ["height", "width", "channels"],
        "info": {
            "video.height": h,
            "video.width": w,
            "video.codec": "h264",
            "video.pix_fmt": "yuv444p",
            "video.is_depth_map": False,
            "video.fps": FPS,
            "video.channels": 3,
            "has_audio": False,
        },
    }
    scalar = {"shape": [1], "names": None}
    return {
        "observation.state": {"dtype": "float32", "shape": [n_state], "names": None},
        "action": {"dtype": "float32", "shape": [n_action], "names": None},
        **{f"observation.images.{c}": video for c in CAMERAS},
        "timestamp": {"dtype": "float32", **scalar},
        "frame_index": {"dtype": "int64", **scalar},
        "episode_index": {"dtype": "int64", **scalar},
        "index": {"dtype": "int64", **scalar},
        "task_index": {"dtype": "int64", **scalar},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", nargs="+", type=Path, default=[Path("datasets/move_plate")])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--max-episodes", type=int, default=0, help="debug: stop after N")
    parser.add_argument("--check", action="store_true", help="decode videos, report error")
    args = parser.parse_args()

    if args.out.exists():
        raise SystemExit(f"{args.out} exists; use a new directory")
    episodes, ep, total, worst = [], 0, 0, 0.0
    for root in args.data:
        rgb = np.load(root / "rgb.npy", mmap_mode="r")
        state = np.load(root / "state.npy", mmap_mode="r")
        action = np.load(root / "action.npy", mmap_mode="r")
        ends = np.load(root / "episode_ends.npy")
        starts = np.concatenate([[0], ends[:-1]])
        if rgb.shape[1] != len(CAMERAS) or state.shape[1] != 50 or action.shape[1] != 20:
            raise ValueError(f"{root}: unexpected shapes {rgb.shape} {state.shape} {action.shape}")
        for s, e in zip(starts, ends, strict=True):
            if args.max_episodes and ep >= args.max_episodes:
                break
            n = int(e - s)
            chunk = ep // CHUNK
            table = pa.table(
                {
                    "observation.state": list(np.asarray(state[s:e], np.float32)),
                    "action": list(np.asarray(action[s:e], np.float32)),
                    "timestamp": np.arange(n, dtype=np.float32) / FPS,
                    "frame_index": np.arange(n, dtype=np.int64),
                    "episode_index": np.full(n, ep, np.int64),
                    "index": np.arange(total, total + n, dtype=np.int64),
                    "task_index": np.zeros(n, np.int64),
                    "annotation.human.task_description": np.zeros(n, np.int64),
                    "next.reward": np.zeros(n, np.float32),
                    "next.done": np.arange(n) == n - 1,
                }
            )
            data_path = args.out / f"data/chunk-{chunk:03d}/episode_{ep:06d}.parquet"
            data_path.parent.mkdir(parents=True, exist_ok=True)
            pq.write_table(table, data_path)
            for i, cam in enumerate(CAMERAS):
                frames = np.asarray(rgb[s:e, i]).transpose(0, 2, 3, 1)
                vpath = (
                    args.out
                    / f"videos/chunk-{chunk:03d}/observation.images.{cam}/episode_{ep:06d}.mp4"
                )
                write_video(vpath, frames)
                if args.check:
                    dec = read_video(vpath)
                    if dec.shape != frames.shape:
                        raise RuntimeError(f"{vpath}: decoded {dec.shape} != {frames.shape}")
                    worst = max(worst, float(np.abs(dec.astype(int) - frames).mean()))
            episodes.append(
                {"episode_index": ep, "tasks": [TASK], "length": n, "source": str(root)}
            )
            ep += 1
            total += n
            print(f"episode {ep:4d}  {root.name:12s} {n:5d} frames", flush=True)

    meta = args.out / "meta"
    meta.mkdir(parents=True, exist_ok=True)
    h, w = rgb.shape[-2:]
    info = {
        "codebase_version": "v2.1",
        "robot_type": "unitree_g1_dex1_bigym2",
        "total_episodes": ep,
        "total_frames": total,
        "total_tasks": 1,
        "total_videos": ep * len(CAMERAS),
        "total_chunks": (ep - 1) // CHUNK + 1,
        "chunks_size": CHUNK,
        "fps": FPS,
        "splits": {"train": f"0:{ep}"},
        "data_path": "data/chunk-{episode_chunk:03d}/episode_{episode_index:06d}.parquet",
        "video_path": "videos/chunk-{episode_chunk:03d}/{video_key}/episode_{episode_index:06d}.mp4",
        "features": feature_info(50, 20, h, w),
    }
    (meta / "info.json").write_text(json.dumps(info, indent=2))
    (meta / "modality.json").write_text(json.dumps(modality_json(), indent=2))
    (meta / "tasks.jsonl").write_text(json.dumps({"task_index": 0, "task": TASK}) + "\n")
    (meta / "episodes.jsonl").write_text("".join(json.dumps(e) + "\n" for e in episodes))
    shutil.copy(Path(__file__).with_name("layout.py"), meta / "layout_snapshot.py")
    print(f"wrote {ep} episodes, {total} frames -> {args.out}")
    if args.check:
        print(f"worst mean |decoded - original| per video: {worst:.3f} (0-255 scale)")


if __name__ == "__main__":
    main()
